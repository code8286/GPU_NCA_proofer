"""Check proof-source hygiene and reproducibly assemble the browser check bundle.

This checks packaging only. Acceptance by Lean is a separate verification step.
"""
from __future__ import annotations

import argparse
import hashlib
import json
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parents[1]
PROJECT = ROOT / "proofs/lean"


def without_comments(source):
    source = re.sub(r"/-.*?-/", "", source, flags=re.DOTALL)
    return re.sub(r"--[^\n]*", "", source)


def bundle():
    aggregator = (PROJECT / "GraphNCA.lean").read_text(encoding="utf-8")
    modules = re.findall(r"^import (GraphNCA\.\w+)$", aggregator, re.MULTILINE)
    if not modules:
        raise ValueError("Proof aggregator contains no modules")
    pieces = ["import Mathlib\n", "/- Generated by scripts/check_lean_sources.py --write-bundle. -/\n"]
    hashes, names = {}, []
    for module in modules:
        path = PROJECT / (module.replace(".", "/") + ".lean")
        text = path.read_text(encoding="utf-8")
        code = without_comments(text)
        if re.search(r"\b(?:sorry|admit|axiom|native_decide|unsafe|run_tac)\b", code):
            raise ValueError(f"Untrusted placeholder/escape in {module}")
        if "skipKernelTC" in code or "implemented_by" in code:
            raise ValueError(f"Kernel bypass in {module}")
        names.extend(re.findall(r"^theorem\s+(\w+)", code, re.MULTILINE))
        hashes[path.relative_to(PROJECT).as_posix()] = hashlib.sha256(path.read_bytes()).hexdigest()
        pieces.extend([f"\n/- SOURCE: {module} -/\n", re.sub(r"^import Mathlib\n", "", text)])
    if len(names) != len(set(names)):
        raise ValueError("Duplicate theorem names")
    pieces.append('\n#eval Lean.versionString\n')
    pieces.extend(f"#print axioms GraphNCA.{name}\n" for name in names)
    pieces.append('#eval "GNN_NCA_PROOF_BUNDLE_COMPLETE"\n')
    return "".join(pieces), hashes, names


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--write-bundle", action="store_true")
    parser.add_argument("--check-record", action="store_true",
                        help="Validate retained browser evidence against current sources; does not rerun Lean")
    args = parser.parse_args()
    expected, hashes, names = bundle()
    path = PROJECT / "BrowserBundle.lean"
    if args.write_bundle:
        path.write_text(expected, encoding="utf-8", newline="\n")
    if not path.exists() or path.read_text(encoding="utf-8") != expected:
        raise ValueError("Stale browser proof bundle; rerun with --write-bundle")
    print(json.dumps({"scope": "Static source/package checks, not Lean type checking",
                      "modules": len(hashes), "theorems": len(names),
                      "bundle_sha256": hashlib.sha256(path.read_bytes()).hexdigest(),
                      "sources_sha256": hashes}, indent=2))
    if args.check_record:
        folder = PROJECT / "verification"
        record = json.loads((folder / "status.json").read_text(encoding="utf-8"))
        if record["bundle_sha256"] != hashlib.sha256(path.read_bytes()).hexdigest() or record["sources_sha256"] != hashes:
            raise ValueError("Retained Lean evidence is stale for current proof sources")
        transcript = (folder / "final-diagnostics.txt").read_text(encoding="utf-8")
        lines = (folder / "axiom-reports.txt").read_text(encoding="utf-8").splitlines()
        actual_names = []
        for line in lines:
            if line not in transcript:
                raise ValueError("Axiom report is absent from the retained transcript")
            match = re.search(r"text ' GraphNCA\.(\w+) ' (.*)", line)
            if not match:
                raise ValueError("Malformed axiom report")
            actual_names.append(match[1])
            tail = match[2]
            if "does not depend on any axioms" in tail:
                continue
            dependencies = re.fullmatch(r"depends on axioms:\s*\[([^]]*)\]\s*", tail)
            if not dependencies:
                raise ValueError("Unrecognized axiom report")
            used = {x.strip() for x in dependencies[1].split(",") if x.strip()}
            if not used <= {"propext", "Classical.choice", "Quot.sound"}:
                raise ValueError(f"Unexpected axiom dependency: {used}")
        if actual_names != names or "GNN_NCA_PROOF_BUNDLE_COMPLETE" not in transcript:
            raise ValueError("Incomplete browser evidence")
        if record["theorems_checked"] != len(names):
            raise ValueError("Recorded theorem count disagrees with source")
        for name, expected_hash in record["evidence_sha256"].items():
            if hashlib.sha256((folder / name).read_bytes()).hexdigest() != expected_hash:
                raise ValueError(f"Changed Lean evidence: {name}")
        print("PASS: retained browser evidence matches current sources and all theorem axiom reports.")
        print("This inspects saved evidence; it does not execute Lean or a local Lake build.")
        print("\n".join(lines))


if __name__ == "__main__":
    main()
